-- ABOUTME: Generates fnl/ezu/unicode-categories.fnl, the general category of
-- ABOUTME: every code point, from Unicode's DerivedGeneralCategory.txt.
--
-- usage: lua tools/unicode-categories.lua VERSION DerivedGeneralCategory.txt > fnl/ezu/unicode-categories.fnl
-- (from https://www.unicode.org/Public/VERSION/ucd/extracted/)

local version, category_file = ...
assert(version and category_file,
       "usage: lua tools/unicode-categories.lua VERSION DerivedGeneralCategory.txt")

local ranges = {}
for line in io.lines(category_file) do
  local lo, hi, cat = line:match("^(%x+)%.%.(%x+)%s*;%s*(%a%a)")
  if not lo then
    lo, cat = line:match("^(%x+)%s*;%s*(%a%a)")
    hi = lo
  end
  if lo then
    table.insert(ranges, {tonumber(lo, 16), tonumber(hi, 16), cat})
  end
end
table.sort(ranges, function(a, b) return a[1] < b[1] end)

-- runs of one category, each from its first code point: the file covers every
-- code point, unassigned ones as Cn
local runs, next_cp = {}, 0
for _, r in ipairs(ranges) do
  assert(r[1] == next_cp, string.format("gap before U+%04X", r[1]))
  if #runs == 0 or runs[#runs][2] ~= r[3] then
    table.insert(runs, {r[1], r[3]})
  end
  next_cp = r[2] + 1
end
assert(next_cp == 0x110000, "the data must reach U+10FFFF")

local lines, line = {}, {}
for _, run in ipairs(runs) do
  table.insert(line, string.format("%X:%s", run[1], run[2]))
  if #line == 12 then
    table.insert(lines, table.concat(line, " "))
    line = {}
  end
end
if #line > 0 then table.insert(lines, table.concat(line, " ")) end

io.write(string.format([=[
;; ABOUTME: The Unicode general category of a code point, from Unicode %s
;; ABOUTME: data: generated by tools/unicode-categories.lua, don't edit.

;; each run of one category, from its first code point: "START:CATEGORY"
(local starts [])
(local categories [])

(each [start category (: "
%s
" :gmatch "(%%x+):(%%a%%a)")]
  (table.insert starts (tonumber start 16))
  (table.insert categories category))

(fn of [cp]
  "The two-letter general category of code point cp (Lu, Nd, Zs, Cn…)."
  (var low 1)
  (var high (length starts))
  ;; the last run starting at or before cp
  (while (< low high)
    (let [mid (// (+ low high 1) 2)]
      (if (<= (. starts mid) cp)
          (set low mid)
          (set high (- mid 1)))))
  (. categories low))

{: of}
]=], version, table.concat(lines, "\n")))
