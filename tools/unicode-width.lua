-- ABOUTME: Generates fnl/atlas/cli/width.fnl, the display width of text in a
-- ABOUTME: terminal, from Unicode's EastAsianWidth.txt and DerivedGeneralCategory.txt.
--
-- usage: lua tools/unicode-width.lua VERSION EastAsianWidth.txt DerivedGeneralCategory.txt > fnl/atlas/cli/width.fnl
-- (files from https://www.unicode.org/Public/VERSION/ucd/, the second under extracted/)

local version, eaw_file, category_file = ...
assert(version and eaw_file and category_file,
       "usage: lua tools/unicode-width.lua VERSION EastAsianWidth.txt DerivedGeneralCategory.txt")

-- ranges [{lo, hi}] of the lines of file whose property is in wanted
local function ranges(file, wanted)
  local out = {}
  for line in io.lines(file) do
    local lo, hi, prop = line:match("^(%x+)%.%.(%x+)%s*;%s*(%w+)")
    if not lo then
      lo, prop = line:match("^(%x+)%s*;%s*(%w+)")
      hi = lo
    end
    if lo and wanted[prop] then
      table.insert(out, {tonumber(lo, 16), tonumber(hi, 16)})
    end
  end
  return out
end

-- sorted, with touching or overlapping ranges joined
local function merged(list)
  table.sort(list, function(a, b) return a[1] < b[1] end)
  local out = {}
  for _, r in ipairs(list) do
    local last = out[#out]
    if last and r[1] <= last[2] + 1 then
      last[2] = math.max(last[2], r[2])
    else
      table.insert(out, {r[1], r[2]})
    end
  end
  return out
end

-- combining and enclosing marks and format characters take no column; the
-- soft hyphen (a format character) is shown as a hyphen
local zero = ranges(category_file, {Mn = true, Me = true, Cf = true})
table.insert(zero, {0x1160, 0x11FF}) -- Hangul medial vowels and final consonants
table.insert(zero, {0xD7B0, 0xD7FF}) -- and their Extended-B forms
table.insert(zero, {0x200B, 0x200B}) -- zero width space
local zero_ranges = {}
for _, r in ipairs(merged(zero)) do
  if r[1] <= 0xAD and 0xAD <= r[2] then
    if r[1] < 0xAD then table.insert(zero_ranges, {r[1], 0xAC}) end
    if r[2] > 0xAD then table.insert(zero_ranges, {0xAE, r[2]}) end
  else
    table.insert(zero_ranges, r)
  end
end

local wide_ranges = merged(ranges(eaw_file, {W = true, F = true}))

local function hex_lines(list)
  local lines, line = {}, {}
  for _, r in ipairs(list) do
    table.insert(line, string.format("%X-%X", r[1], r[2]))
    if #line == 8 then
      table.insert(lines, table.concat(line, " "))
      line = {}
    end
  end
  if #line > 0 then table.insert(lines, table.concat(line, " ")) end
  return table.concat(lines, "\n")
end

io.write(string.format([=[
;; ABOUTME: Display width of text in a terminal, from Unicode %s data:
;; ABOUTME: generated by tools/unicode-width.lua, don't edit.

(fn parse-ranges [text]
  "[lo hi lo hi ...] from \"LO-HI LO-HI ...\" in hexadecimal."
  (let [out []]
    (each [lo hi (text:gmatch "(%%x+)%%-(%%x+)")]
      (table.insert out (tonumber lo 16))
      (table.insert out (tonumber hi 16)))
    out))

;; marks and format characters, which take no column
(local zero (parse-ranges "
%s
"))

;; East Asian wide and fullwidth characters, which take two columns
(local wide (parse-ranges "
%s
"))

(fn in-ranges? [ranges cp]
  "Whether cp is in one of ranges, [lo hi lo hi ...] sorted: binary search."
  (var low 1)
  (var high (// (length ranges) 2))
  (var found false)
  (while (and (not found) (<= low high))
    (let [mid (// (+ low high) 2)
          lo (. ranges (- (* mid 2) 1))
          hi (. ranges (* mid 2))]
      (if (< cp lo) (set high (- mid 1))
          (> cp hi) (set low (+ mid 1))
          (set found true))))
  found)

(fn char-width [cp last joined]
  "Columns cp takes after a character of width last; joined: cp follows a
zero width joiner after an emoji."
  (if joined 0
      (= cp 0xFE0F) (if (= last 1) 1 0)
      (and (<= 0x1F3FB cp) (<= cp 0x1F3FF) (> last 0)) 0
      (in-ranges? zero cp) 0
      (in-ranges? wide cp) 2
      1))

(fn sequence-width [s]
  (var n 0)
  (var last 0)
  (var joined false)
  (each [_ cp (utf8.codes s)]
    (let [w (char-width cp last joined)]
      ;; joiners join emoji; between letters they hide nothing
      (set joined (and (= cp 0x200D) (= last 2)))
      (set n (+ n w))
      (when (> w 0)
        (set last (if (= cp 0xFE0F) 2 w)))))
  n)

(fn of [s]
  "Columns s takes in a terminal; text that isn't UTF-8 counts a column a
byte. As terminals show emoji sequences: U+FE0F makes the character before it
an emoji, two columns; what a zero width joiner joins, and skin tones, add
nothing."
  (if (utf8.len s) (sequence-width s) (length s)))

{: of}
]=], version, hex_lines(zero_ranges), hex_lines(wide_ranges)))
